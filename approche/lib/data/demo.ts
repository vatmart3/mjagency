const day = (offset: number, hour = 10, min = 0) => {
  const d = new Date();
  d.setDate(d.getDate() + offset);
  d.setHours(hour, min, 0, 0);
  return d.toISOString();
};
const date = (offset: number) => day(offset).slice(0, 10);

